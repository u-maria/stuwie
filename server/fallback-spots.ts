export function getFallbackSpots(filters: {
  district?: string;
  status?: string;
  hasWifi?: string;
  hasOutlets?: string;
} = {}): SpotsListResponse {
  return fallbackSpots.filter((spot) => {
    if (filters.status && spot.status !== filters.status) return false;
    if (filters.district && spot.district !== filters.district) return false;
    if (filters.hasWifi === "true" && !spot.hasWifi) return false;
    if (filters.hasOutlets === "true" && !spot.hasOutlets) return false;
    return spot.status === "approved";
  });
}

export function getFallbackSpot(id: number) {
  return fallbackSpots.find((spot) => spot.id === id);
}